// The dossier (phase-3 design §4.2.3, Pass B; §4.2 Pass C): its record at the playhead (turns,
// messages, betrayals) and its score and cities hour by hour (Pass C, `dossier-extras.tsx`), who
// plays it (model and effort, a bot, or a fake model), whether it was handed to a bot, what it has
// spent against its cap (when costs are served), who the player is (its profile: goal,
// temperament, attitude to its word, style), its notebook at the playhead and the history of its
// changes (Pass C), and its public thoughts, each with that turn's reasoning behind an expander.

type TurnItem = FeedItemOf<"turn">;
const THOUGHTS = 30;

function Section({
  title,
  icon: Icon,
  children,
}: {
  readonly title: string;
  readonly icon: typeof Brain;
  readonly children: ReactNode;
}) {
  return (
    <section className="flex flex-col gap-1.5">
      <h3 className="text-muted-foreground flex items-center gap-1.5 text-xs font-semibold tracking-wider uppercase">
        <Icon className="size-3.5" aria-hidden="true" /> {title}
      </h3>
      {children}
    </section>
  );
}

function Profile({ seat }: { readonly seat: SeatInfo }) {
  const p = seat.profile;
  if (p === null) {
    return (
      <p className="text-muted-foreground text-sm">
        {seat.kind === "bot"
          ? "A scripted bot: it follows a fixed strategy and has no profile."
          : "No profile was published for this seat."}
      </p>
    );
  }
  const rows: readonly [string, string][] = [
    ["Goal", p.goal],
    ["Temperament", p.temperament],
    ["Its word", p.word],
    ["Style", p.style],
  ];
  return (
    <div className="flex flex-col gap-1.5 text-sm">
      <p className="font-medium italic">
        <PlainText text={p.name} />
      </p>
      <dl className="flex flex-col gap-1.5">
        {rows.map(([k, v]) => (
          <div key={k}>
            <dt className="text-muted-foreground text-xs">{k}</dt>
            <dd>
              <PlainText text={v} />
            </dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

function WhoPlays({
  seat,
  dossier,
}: {
  readonly seat: SeatInfo;
  readonly dossier: PlayerDossier | null;
}) {
  const id = seat.seat;
  const handoff = useMatch((s) => (isPlayerId(id) ? (s.frame?.seats[id]?.handoff ?? null) : null));
  const fake = isFakeSeat(seat);
  const published = usePublished();
  const spent = dossier?.spentNanoUsd ?? null;
  const cap = dossier?.capNanoUsd ?? null;
  return (
    <div className="flex flex-col gap-1.5 text-sm">
      <p className="flex flex-wrap items-center gap-2">
        <ModelBadge seat={seat} />
        <span>{playedBy(seat)}</span>
      </p>
      {fake ? (
        <p className="text-muted-foreground text-xs">
          A fake run: a scripted bot plays behind the language-model pipe, so its “thoughts” and
          reasoning are generated by the bot, not by a model.
        </p>
      ) : null}
      {handoff === null ? (
        seat.handoffBot === null ? null : (
          <p className="text-muted-foreground text-xs">
            If it runs out of budget, the bot <span className="font-mono">{seat.handoffBot}</span>{" "}
            takes over.
          </p>
        )
      ) : (
        <p className="flex items-center gap-1.5 text-xs">
          <Bot className="size-3.5 shrink-0" aria-hidden="true" />
          Handed to the bot <span className="font-mono">{handoff.label}</span> at{" "}
          <GameTime t={handoff.t} />.
        </p>
      )}
      {spent === null ? (
        seat.kind === "llm" && !published.costs ? (
          <NotPublished what="Spending" />
        ) : null
      ) : (
        <div className="flex flex-col gap-1" data-testid="spend">
          <p className="flex items-center gap-1.5 text-xs">
            <Coins className="text-gold size-3.5 shrink-0" aria-hidden="true" />
            Spent {fmtUsd(spent)}
            {cap === null ? null : <> of its {fmtUsd(cap)} cap</>}
            {fake ? <span className="text-muted-foreground"> (simulated prices)</span> : null}
          </p>
          {cap === null || cap <= 0 ? null : (
            <div aria-hidden="true" className="bg-muted h-1.5 overflow-hidden rounded-full">
              <span
                className="bg-gold block h-full"
                style={{ width: `${Math.min(100, (spent / cap) * 100)}%` }}
              />
            </div>
          )}
        </div>
      )}
    </div>
  );
}

function Thought({ item, llm }: { readonly item: TurnItem; readonly llm: boolean }) {
  return (
    <li className="border-border/60 flex flex-col gap-1 border-t pt-2 first:border-t-0 first:pt-0">
      <p className="text-muted-foreground text-[0.7rem]">
        turn {item.turn} · <GameTime t={item.t} />
        {item.reasons.length === 0 ? null : (
          <> · woke for {item.reasons.map(wakeWords).join("; ")}</>
        )}
      </p>
      {item.thought === null || item.thought === "" ? (
        <p className="text-muted-foreground text-xs">(no thought)</p>
      ) : (
        <PlainText text={item.thought} className="block text-sm" />
      )}
      {llm ? (
        <ReasoningToggle seat={item.seat} turn={item.turn} />
      ) : (
        <OpenTurnButton seat={item.seat} turn={item.turn} />
      )}
    </li>
  );
}

function Thoughts({ seat }: { readonly seat: SeatInfo }) {
  const feed = useFeed();
  const [all, setAll] = useState(false);
  const turns = useMemo(() => turnsOf(feed, seat.seat).toReversed(), [feed, seat.seat]);
  const shown = all ? turns : turns.slice(0, THOUGHTS);
  if (turns.length === 0) {
    return <p className="text-muted-foreground text-sm">No turn has ended yet at this time.</p>;
  }
  return (
    <>
      <ol className="flex flex-col gap-2">
        {shown.map((t) => (
          <Thought key={t.id} item={t} llm={seat.kind === "llm"} />
        ))}
      </ol>
      {turns.length > shown.length ? (
        <button
          type="button"
          onClick={() => setAll(true)}
          className="text-primary hover:text-primary/80 text-xs font-medium"
        >
          Show all {fmtInt(turns.length)} turns
        </button>
      ) : null}
    </>
  );
}

/**
 * While a live match is followed, the dossier is fetched again when the seat opens a turn or a game
 * hour passes (its hourly points and notebook grow on the server; the route's 10 s `max-age` bounds
 * the requests); a replay reads the one it has.
 */
function useLiveDossier(id: PlayerId | null): void {
  const live = useMatch((s) => s.mode === "live");
  const turn = useMatch((s) => (id === null ? 0 : (s.frame?.seats[id]?.turn ?? 0)));
  const hour = useMatch((s) => Math.floor((s.frame?.t ?? 0) / 3_600));
  const last = useRef<string | null>(null);
  useEffect(() => {
    const key = `${id ?? ""}:${turn}:${hour}`;
    if (last.current !== null && last.current !== key && live && id !== null) {
      loaders.dossier(id);
    }
    last.current = key;
  }, [id, turn, hour, live]);
}

function Body({ seat }: { readonly seat: SeatInfo }) {
  const id: PlayerId | null = isPlayerId(seat.seat) ? seat.seat : null;
  const d = useDossier(id);
  useLiveDossier(id);
  const dossier = d?.status === "ok" ? d.value : null;
  const rank = useMatch((s) => (id === null ? null : (s.frame?.players[id] ?? null)));
  const failed =
    d?.status === "error" ? (
      <p className="text-muted-foreground text-xs">The dossier could not be loaded.</p>
    ) : null;
  return (
    <div className="flex flex-col gap-5 px-4 pb-6">
      {rank === null ? null : (
        <p className="text-sm">
          Rank <strong>{rank.rank}</strong> · {fmtInt(rank.score)} points ·{" "}
          {plural(rank.cities, "city", "cities")}
          {rank.alive ? null : <span className="text-betrayal"> · eliminated</span>}
        </p>
      )}
      {id === null ? null : (
        <Section title="Record" icon={Swords}>
          <SeatRecord seat={id} />
        </Section>
      )}
      <Section title="Hour by hour" icon={ChartLine}>
        {failed ?? <HourlyCharts dossier={dossier} color={playerColor(seat.color)} />}
      </Section>
      <Section title="Who plays it" icon={Bot}>
        <WhoPlays seat={seat} dossier={dossier} />
      </Section>
      <Section title="Profile" icon={UserRound}>
        <Profile seat={seat} />
      </Section>
      <Section title="Notebook at this time" icon={NotebookPen}>
        {failed ?? <NotebookAt dossier={dossier} />}
      </Section>
      <Section title="Notebook history" icon={History}>
        {failed ?? <NotebookHistory dossier={dossier} />}
      </Section>
      <Section title="Thoughts, newest first" icon={Brain}>
        <Thoughts seat={seat} />
      </Section>
    </div>
  );
}

export function PlayerSheet() {
  const selected = useUi((s) => s.selectedPlayer);
  const seat = useSeat(selected ?? "");
  return (
    <Sheet
      open={selected !== null}
      onOpenChange={(open) => (open ? undefined : uiActions.closePlayer())}
    >
      <SheetContent data-testid="player-sheet" className="w-full overflow-y-auto sm:max-w-md">
        <SheetHeader>
          <SheetTitle className="flex items-center gap-2 pr-6 text-lg">
            {seat === null ? (
              "Player"
            ) : (
              <>
                <PlayerGlyph color={seat.color} size={16} />
                <bdi className="truncate">{seat.name}</bdi>
                <span className="text-muted-foreground font-mono text-base font-normal">
                  · {seat.seat}
                </span>
              </>
            )}
          </SheetTitle>
          <SheetDescription>
            {seat === null ? "Dossier" : `Dossier of ${seat.name} (${seat.seat})`}
          </SheetDescription>
        </SheetHeader>
        {seat === null ? null : <Body key={seat.seat} seat={seat} />}
      </SheetContent>
    </Sheet>
  );
}
